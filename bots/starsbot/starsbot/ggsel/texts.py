# Общие тексты с FunPay-обращениями: заменяем название площадки и номер заказа
_REPLACE = (("FunPay", "GGSEL"), ("фанпей", "GGSEL"), ("Фанпей", "GGSEL"))
_LINK_RE = re.compile(r"(https?://|www\.|t\.me/|telegram\.me/)\S*", re.I)


def sanitize(text: str) -> str:
    """Убирает то, что запрещено в чате GGSEL: упоминания других площадок и любые ссылки."""
    for a, b in _REPLACE:
        text = text.replace(a, b)
    return _LINK_RE.sub("", text).strip()


def has_link(text: str) -> bool:
    return bool(_LINK_RE.search(text or ""))


