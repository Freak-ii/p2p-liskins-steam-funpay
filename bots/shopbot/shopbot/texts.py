def faq_text(expandable: bool = True) -> str:
    q = "<blockquote expandable>" if expandable else "<blockquote>"
    body = "\n".join(f"<b>{i}. {a}</b>\n{q}{b}</blockquote>" for i, (a, b) in enumerate(FAQ_ITEMS, 1))
    return "❓ <b>Вопросы и ответы</b>\nНажмите на ответ, чтобы раскрыть его.\n\n" + body

